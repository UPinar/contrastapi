#ifndef WATCHLIST_PACKAGE_CHECK_H
#define WATCHLIST_PACKAGE_CHECK_H

#include "package.h"

typedef struct {
  char  ma_ecosystem[PACKAGECHECK_ECOSYSTEM_MAX_LEN + 1];
  char  ma_name[PACKAGECHECK_NAME_MAX_LEN + 1];
  char  ma_version[PACKAGECHECK_VERSION_MAX_LEN + 1];
} WATCHLISTPACKAGECHECKItem_t;

#define WATCHLIST_PACKAGE_CHECK_ADVISORY_ID_MAX_LEN 48

#define WATCHLIST_PACKAGE_CHECK_ADVISORY_SOURCE_MAX_LEN 7

#define WATCHLIST_PACKAGE_CHECK_ADVISORY_ALIAS_MAX_COUNT 64
#define WATCHLIST_PACKAGE_CHECK_ADVISORY_ALIAS_MAX_LEN   64

#define WATCHLIST_PACKAGE_CHECK_ADVISORY_ALIASES_JSON_MAX_LEN \
  (2 + WATCHLIST_PACKAGE_CHECK_ADVISORY_ALIAS_MAX_COUNT * (2 * WATCHLIST_PACKAGE_CHECK_ADVISORY_ALIAS_MAX_LEN + 2) + (WATCHLIST_PACKAGE_CHECK_ADVISORY_ALIAS_MAX_COUNT - 1) * 2)

#define WATCHLIST_PACKAGE_CHECK_ADVISORY_CVE_FACTS_JSON_MAX_LEN (WATCHLIST_PACKAGE_CHECK_ADVISORY_ALIAS_MAX_COUNT * 512)

#define WATCHLIST_PACKAGE_CHECK_ATTRIBUTION_JSON_MAX_LEN 4096

typedef struct {
  char ma_advisoryId[WATCHLIST_PACKAGE_CHECK_ADVISORY_ID_MAX_LEN + 1];
  char ma_fixedVersion[PACKAGECHECK_VERSION_MAX_LEN + 1];
} WATCHLISTPACKAGECHECKChange_t;

typedef struct {
  char  ma_advisoryId[WATCHLIST_PACKAGE_CHECK_ADVISORY_ID_MAX_LEN + 1];
  char  ma_source[WATCHLIST_PACKAGE_CHECK_ADVISORY_SOURCE_MAX_LEN + 1];
  char* mp_aliases;
} WATCHLISTPACKAGECHECKAdvisory_t;

#endif
